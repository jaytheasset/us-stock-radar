import {readFileSync,writeFileSync,readdirSync,existsSync} from 'node:fs';
import {join} from 'node:path';
import assert from 'node:assert/strict';
import {enqueueOsSnapshot,readSnapshot} from '../lib/sec-os-snapshot/repository.ts';
import {CodexCliOsSnapshotProvider} from '../lib/sec-os-snapshot/provider.ts';
import {processSnapshot} from '../lib/sec-os-snapshot/runtime.ts';
const out=process.argv[2],exe=process.env.OS_SNAPSHOT_CODEX_EXECUTABLE;
if(!out||!exe)throw Error('Evidence path and native Codex executable required');
const setup=JSON.parse(readFileSync(join(out,'setup.json'),'utf8'));
const queued=await enqueueOsSnapshot(setup.rawItemId);
writeFileSync(join(out,'enqueue.json'),JSON.stringify(queued,null,2));
const provider=new CodexCliOsSnapshotProvider({executable:exe,root:join(out,'journal')});
const processStarts=()=>readdirSync(provider.root,{withFileTypes:true}).filter(d=>d.isDirectory()).flatMap(d=>readdirSync(join(provider.root,d.name)).map(attempt=>({runId:d.name,path:join(provider.root,d.name,attempt,'started.json')}))).filter(m=>existsSync(m.path)&&JSON.parse(readFileSync(m.path,'utf8')).pid>0);
const result=await processSnapshot(queued.id,provider);
const snapshot=await readSnapshot(queued.id);
writeFileSync(join(out,'result.json'),JSON.stringify({result,runId:queued.id,status:snapshot.run.metadata.osStatus,current:snapshot.current},null,2));
const startsBeforeReplay=processStarts().length;
const replay=await enqueueOsSnapshot(setup.rawItemId);assert.equal(replay.id,queued.id);
await processSnapshot(queued.id,{run:async()=>{throw Error('Reenqueue called provider');}});
const attempts=readdirSync(join(out,'journal',queued.id));
assert.equal(attempts.length,1);assert.ok(['PASS','REVIEW_REQUIRED','NO_DIRECT_CURRENT_OS'].includes(snapshot.run.metadata.osStatus));
const starts=processStarts(),codexCalls=starts.filter(s=>s.runId===queued.id).length,additional=starts.length-startsBeforeReplay;
assert.equal(codexCalls,1);assert.equal(additional,0);
const report={status:snapshot.run.metadata.osStatus,runId:queued.id,codexCalls,totalJournalProcessStarts:starts.length,reenqueueAdditionalCalls:additional,validation:snapshot.run.metadata.osCheckpoint.validation,current:snapshot.current};
writeFileSync(join(out,'e2e-report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify({...report,validation:report.validation.stage}));
