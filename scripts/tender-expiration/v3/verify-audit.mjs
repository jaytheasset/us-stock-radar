// Offline integrity/identity audit. Does not choose or grade SEC meanings.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { verifyFrozen, runId } from './run.mjs';
import { validateOutput } from './contract.ts';
import { hash, resolveProvenance } from './boundary.mjs';
const dir = fileURLToPath(new URL('./', import.meta.url));
const json = async path => JSON.parse(await readFile(join(dir, path), 'utf8'));
const prepared = await verifyFrozen();
const started = await json('run/started.json');
assert.equal(started.requestHash, hash(prepared.body));
assert.equal(started.mappingHash, prepared.frozenMapHash);
const provider = await json('run/provider-response.txt');
const raw = await readFile(join(dir, 'run/structured.txt'), 'utf8');
assert.equal(raw, provider.candidates[0].content.parts.filter(p => typeof p.text === 'string' && !p.thought).map(p => p.text).join(''));
const audit = await json('run/audit.json');
const validation = validateOutput(raw, prepared.providerSource.evidence.map(e => e.ref));
assert.deepEqual(audit.validation, validation);
assert.ok(validation.providerSchema.valid && validation.local.valid);
const provenance = resolveProvenance({ raw, ...prepared });
assert.deepEqual(await json('run/provenance-audit.json'), provenance);
assert.equal(provenance.valid, true);
const ledger = await json('run/ledger.json');
assert.equal(ledger.physicalCalls, 1);
assert.equal(ledger.otherFilingsExecuted, 0);
assert.deepEqual(ledger.cases, [audit]);
console.log(JSON.stringify({ runId, auditIntegrity: 'PASS', v1v2ByteIdentical: 'PASS', requestSourceSchemaMapFrozen: 'PASS', rawUnchanged: 'PASS', physicalCalls: ledger.physicalCalls, otherFilingsExecuted: 0, providerSchema: 'PASS', localStrict: 'PASS', provenanceMapping: 'PASS', resolvedRefs: provenance.resolved.map(e => e.ref), semanticReview: 'separate manual source review in semantic-review.json; not determined by this checker' }, null, 2));
