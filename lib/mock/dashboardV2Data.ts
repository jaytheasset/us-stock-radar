export type DashboardV2EventType =
  | "earnings"
  | "legal"
  | "insider"
  | "ma"
  | "listing"
  | "product"
  | "govt"
  | "dilution";

export type DashboardV2Impact = "major" | "high" | "medium" | "low";

export type DashboardV2MarketMover = {
  rank: number;
  ticker: string;
  company: string;
  price: string;
  changePercent: string;
  volume: string;
  marketCap: string;
  events: DashboardV2EventType[];
  maxImpact: DashboardV2Impact;
  selected?: boolean;
};

export type DashboardV2TimelineEvent = {
  id: string;
  type: DashboardV2EventType;
  title: string;
  timestamp: string;
  impact: Exclude<DashboardV2Impact, "major" | "low">;
};

export type DashboardV2Candle = {
  time: string;
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number;
};

export type DashboardV2TickerDetail = {
  ticker: string;
  company: string;
  price: string;
  changePercent: string;
  changeAmount: string;
  badges: DashboardV2EventType[];
  ohlc: {
    open: string;
    high: string;
    low: string;
    close: string;
  };
  candles: DashboardV2Candle[];
  recentEvents: DashboardV2TimelineEvent[];
};

