test('unmaterialized peer lookup never substitutes a newer Offering run, another raw filing or a missing O/S',async()=>{
 for(const kind of ['offering','raw','os']){
  const f=await fixture();f.state.stored=null;
  if(kind==='offering')f.input.offering.id=id(30);
  else if(kind==='raw')f.input.raw={...f.raw,id:id(31)};
  else (f.input as any).os=null;
  assert.deepEqual(await readOfferingImpact(id(3),f.repo),{osRunId:null,history:null});
  const rpc=f.calls.filter(c=>c.kind==='rpc');assert.equal(rpc.length,1);
  assert.deepEqual(rpc[0].query,{p_raw_id:id(1)});
 }
});

